function getInitialLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'ru' || stored === 'uk' || stored === 'es') return stored;
  } catch {
    /* storage unavailable */
  }
  const lang = (navigator.language || 'en').toLowerCase();
  if (lang.startsWith('ru')) return 'ru';
  if (lang.startsWith('uk')) return 'uk';
  if (lang.startsWith('es')) return 'es';
  return 'en';
}

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

export const useLocale = create<LocaleState>((set) => {
  const initial = getInitialLocale();
  document.documentElement.lang = initial;
  return {
    locale: initial,
    setLocale: (l) => {
      try {
        localStorage.setItem(STORAGE_KEY, l);
      } catch {
        /* best-effort */
      }
      document.documentElement.lang = l;
      set({ locale: l });
    },
  };
});

export type TranslationKey = Key;

// Reactive hook for components: re-renders on locale change.
export function useT() {
  const locale = useLocale((s) => s.locale);
  return (key: Key): string => translations[locale][key] ?? en[key] ?? key;
}

// Non-reactive helper for code outside React components (toasts, utils).
export function t(key: Key): string {
  const { locale } = useLocale.getState();
  return translations[locale][key] ?? en[key] ?? key;
}
